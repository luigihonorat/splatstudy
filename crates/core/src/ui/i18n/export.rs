//! Strings for exporting the timelapse.

pub struct ExportTr {
    /// The export window's title.
    pub title: &'static str,
    /// In the file → export menu.
    pub menu_item: &'static str,
    /// In the timelapse panel.
    pub panel_item: &'static str,
    pub layout: &'static str,
    pub side_by_side: &'static str,
    pub stacked: &'static str,
    pub sculpt_only: &'static str,
    /// The frame's proportions.
    pub frame: &'static str,
    pub wide: &'static str,
    pub square: &'static str,
    pub tall: &'static str,
    pub speed: &'static str,
    /// Before the target lengths, as "fit to 15 s 30 s 60 s".
    pub fit_to: &'static str,
    /// After a number of seconds, as "15 s".
    pub seconds: &'static str,
    /// Before the video's length, as "length 0:42".
    pub length: &'static str,
    /// How the camera moves during the timelapse.
    pub camera: &'static str,
    /// The view as it is now, all along.
    pub fixed: &'static str,
    /// Slow turns around the clay all through the video.
    pub turntable: &'static str,
    /// One turn around the finished clay before the end card.
    pub turn_at_end: &'static str,
    /// What is shown over the views.
    pub show: &'static str,
    /// The reference laid over the sculpt, as in the view menu.
    pub ghost: &'static str,
    /// The session's elapsed time in a corner.
    pub elapsed: &'static str,
    /// A title at the start of the video.
    pub title_item: &'static str,
    pub file: &'static str,
    pub video: &'static str,
    pub images: &'static str,
    /// While the browser is asked whether it can encode video.
    pub checking: &'static str,
    pub no_video: &'static str,
    pub images_zip: &'static str,
    pub images_folder: &'static str,
    /// Starts the export.
    pub start: &'static str,
    pub cancel: &'static str,
    /// After the counts, as "120 / 900 frames".
    pub frames: &'static str,
    pub exported: &'static str,
    pub images_written: &'static str,
    pub failed: &'static str,
    pub nothing_recorded: &'static str,
    /// The reference was changed or removed while exporting.
    pub reference_changed: &'static str,
    /// Before "(10 fps)": a long video's images are fewer per second so
    /// they fit in the zip.
    pub zip_fewer: &'static str,
    /// The images would not fit in a zip even at the lowest rate.
    pub zip_too_long: &'static str,
    /// The end card's last line, before the site's address.
    pub made_with: &'static str,
    /// Before the file and the system's reason, when a save or write failed.
    pub write_failed: &'static str,
}

